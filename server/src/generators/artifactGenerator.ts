import { DevOpsBlueprint, GeneratedArtifact } from '../types/index.js';

export class ArtifactGenerator {
  public static generateAll(blueprint: DevOpsBlueprint): GeneratedArtifact[] {
    const artifacts: GeneratedArtifact[] = [];
    const appName = blueprint.config.app.name || blueprint.repositoryName;
    const port = blueprint.config.app.port || 80;
    const target = blueprint.config.registry.target || 'ghcr.io/khandaitpiyush';
    const namespace = blueprint.config.deployment.namespace || 'production';
    const replicas = blueprint.config.deployment.replicas || 3;
    const cpuLimit = blueprint.config.deployment.resources?.cpu || '500m';
    const memLimit = blueprint.config.deployment.resources?.memory || '512Mi';

    // 1. Dockerfile
    artifacts.push({
      id: `art-docker-${blueprint.id}`,
      blueprintId: blueprint.id,
      blueprintVersion: blueprint.version,
      repositoryId: blueprint.repositoryId,
      filename: 'Dockerfile',
      fileType: 'dockerfile',
      language: 'dockerfile',
      status: 'generated',
      updatedAt: new Date().toISOString(),
      content: `# Production multi-stage Docker build for ${appName}
# Generated by Unified DevOps Automation Platform

FROM node:22-alpine AS builder
WORKDIR /app

# Cache dependencies
COPY package*.json ./
RUN npm ci --prefer-offline

# Copy source and compile
COPY . .
RUN npm run build

# Stage 2: Minimal hardened production web server
FROM nginx:1.27-alpine AS runner
WORKDIR /usr/share/nginx/html

# Clean default assets and inject compiled build
RUN rm -rf ./*
COPY --from=builder /app/dist .

# Non-root security configuration
USER nginx
EXPOSE ${port}

HEALTHCHECK --interval=30s --timeout=5s --start-period=5s --retries=3 \\
  CMD wget --quiet --tries=1 --spider http://localhost:${port}/ || exit 1

CMD ["nginx", "-g", "daemon off;"]`,
    });

    // 2. Jenkinsfile (Declarative 9-stage pipeline)
    artifacts.push({
      id: `art-jenkins-${blueprint.id}`,
      blueprintId: blueprint.id,
      blueprintVersion: blueprint.version,
      repositoryId: blueprint.repositoryId,
      filename: 'Jenkinsfile',
      fileType: 'jenkinsfile',
      language: 'groovy',
      status: 'generated',
      updatedAt: new Date().toISOString(),
      content: `// Unified DevOps Automation — Autonomous 9-Stage CI/CD Pipeline
// Project: ${appName} | Target: ${blueprint.deploymentTarget}

pipeline {
    agent {
        label 'kubernetes-runner'
    }

    environment {
        REGISTRY = '${target}'
        IMAGE_NAME = '${appName}'
        NAMESPACE = '${namespace}'
        IMAGE_TAG = "\${env.BUILD_NUMBER}"
        SONAR_PROJECT_KEY = "${blueprint.config.security.sonarqube.projectKey || appName}"
    }

    options {
        timeout(time: 30, unit: 'MINUTES')
        buildDiscarder(logRotator(numToKeepStr: '50'))
        disableConcurrentBuilds()
    }

    stages {
        stage('1. Checkout Source') {
            steps {
                echo "Fetching repository source code..."
                checkout scm
            }
        }

        stage('2. Install Dependencies') {
            steps {
                echo "Restoring dependencies from lockfile..."
                sh '${blueprint.config.build.tool === 'npm' ? 'npm ci --prefer-offline' : 'npm install'}'
            }
        }

        stage('3. Run Tests & Lint') {
            steps {
                echo "Executing unit tests and static type checking..."
                sh '${blueprint.config.test.command || 'npm run lint && npm test'}'
            }
        }

        stage('4. SonarQube Analysis') {
            when {
                expression { return ${blueprint.config.security.sonarqube.enabled}; }
            }
            steps {
                withSonarQubeEnv('SonarQube-Server') {
                    sh 'sonar-scanner -Dsonar.projectKey=\${SONAR_PROJECT_KEY} -Dsonar.sources=src'
                }
                timeout(time: 5, unit: 'MINUTES') {
                    waitForQualityGate abortPipeline: true
                }
            }
        }

        stage('5. Trivy Security Scan') {
            when {
                expression { return ${blueprint.config.security.trivy.enabled}; }
            }
            steps {
                echo "Scanning container and dependencies for CVEs..."
                sh 'trivy fs --severity CRITICAL,HIGH --exit-code 1 --no-progress .'
            }
        }

        stage('6. Build Docker Image') {
            steps {
                echo "Building container image \${REGISTRY}/\${IMAGE_NAME}:\${IMAGE_TAG}..."
                sh "docker build -t \${REGISTRY}/\${IMAGE_NAME}:\${IMAGE_TAG} -t \${REGISTRY}/\${IMAGE_NAME}:latest ."
            }
        }

        stage('7. Push Image to GHCR') {
            steps {
                withCredentials([usernamePassword(credentialsId: 'ghcr-credentials', usernameVariable: 'GHCR_USER', passwordVariable: 'GHCR_TOKEN')]) {
                    sh "echo \${GHCR_TOKEN} | docker login ghcr.io -u \${GHCR_USER} --password-stdin"
                    sh "docker push \${REGISTRY}/\${IMAGE_NAME}:\${IMAGE_TAG}"
                    sh "docker push \${REGISTRY}/\${IMAGE_NAME}:latest"
                }
            }
        }

        stage('8. Deploy to Kubernetes') {
            steps {
                echo "Applying Kubernetes manifests to namespace \${NAMESPACE}..."
                sh "kubectl apply -f k8s/ -n \${NAMESPACE}"
                sh "kubectl set image deployment/\${IMAGE_NAME} \${IMAGE_NAME}=\${REGISTRY}/\${IMAGE_NAME}:\${IMAGE_TAG} -n \${NAMESPACE}"
                sh "kubectl rollout status deployment/\${IMAGE_NAME} -n \${NAMESPACE} --timeout=120s"
            }
        }

        stage('9. Record Telemetry & Metadata') {
            steps {
                echo "Recording execution metrics to Platform Observability Hub..."
                sh "curl -s -X POST http://devops-api.internal:5000/api/pipelines/telemetry -d '{\\"build\\": \\"\${IMAGE_TAG}\\", \\"status\\": \\"success\\"}' -H 'Content-Type: application/json'"
            }
        }
    }

    post {
        always {
            cleanWs()
        }
        failure {
            echo "Pipeline failed. Alerting engineering team via webhook..."
        }
    }
}`,
    });

    // 3. k8s/deployment.yaml
    artifacts.push({
      id: `art-k8s-dep-${blueprint.id}`,
      blueprintId: blueprint.id,
      blueprintVersion: blueprint.version,
      repositoryId: blueprint.repositoryId,
      filename: 'k8s/deployment.yaml',
      fileType: 'k8s_deployment',
      language: 'yaml',
      status: 'generated',
      updatedAt: new Date().toISOString(),
      content: `apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${appName}
  namespace: ${namespace}
  labels:
    app.kubernetes.io/name: ${appName}
    app.kubernetes.io/managed-by: unified-devops-platform
    app.kubernetes.io/version: "${blueprint.version}"
spec:
  replicas: ${replicas}
  strategy:
    type: RollingUpdate
    rollingUpdate:
      maxSurge: 1
      maxUnavailable: 0
  selector:
    matchLabels:
      app: ${appName}
  template:
    metadata:
      labels:
        app: ${appName}
    spec:
      containers:
        - name: app
          image: ${target}/${appName}:latest
          imagePullPolicy: IfNotPresent
          ports:
            - containerPort: ${port}
              name: http
          resources:
            requests:
              cpu: 100m
              memory: 128Mi
            limits:
              cpu: ${cpuLimit}
              memory: ${memLimit}
          livenessProbe:
            httpGet:
              path: /
              port: ${port}
            initialDelaySeconds: 15
            periodSeconds: 20
            timeoutSeconds: 5
            failureThreshold: 3
          readinessProbe:
            httpGet:
              path: /
              port: ${port}
            initialDelaySeconds: 5
            periodSeconds: 10
            timeoutSeconds: 3
            failureThreshold: 2
          securityContext:
            readOnlyRootFilesystem: false
            runAsNonRoot: true
            allowPrivilegeEscalation: false`,
    });

    // 4. k8s/service.yaml
    artifacts.push({
      id: `art-k8s-svc-${blueprint.id}`,
      blueprintId: blueprint.id,
      blueprintVersion: blueprint.version,
      repositoryId: blueprint.repositoryId,
      filename: 'k8s/service.yaml',
      fileType: 'k8s_service',
      language: 'yaml',
      status: 'generated',
      updatedAt: new Date().toISOString(),
      content: `apiVersion: v1
kind: Service
metadata:
  name: ${appName}-svc
  namespace: ${namespace}
  labels:
    app.kubernetes.io/name: ${appName}
spec:
  type: ${blueprint.config.deployment.serviceType || 'ClusterIP'}
  ports:
    - port: 80
      targetPort: ${port}
      protocol: TCP
      name: http
  selector:
    app: ${appName}
---
apiVersion: networking.k8s.io/v1
kind: Ingress
metadata:
  name: ${appName}-ingress
  namespace: ${namespace}
  annotations:
    kubernetes.io/ingress.class: nginx
    cert-manager.io/cluster-issuer: letsencrypt-prod
spec:
  rules:
    - host: ${appName}.platform.internal
      http:
        paths:
          - path: /
            pathType: Prefix
            backend:
              service:
                name: ${appName}-svc
                port:
                  number: 80`,
    });

    // 5. terraform/main.tf
    artifacts.push({
      id: `art-tf-${blueprint.id}`,
      blueprintId: blueprint.id,
      blueprintVersion: blueprint.version,
      repositoryId: blueprint.repositoryId,
      filename: 'terraform/main.tf',
      fileType: 'terraform_main',
      language: 'hcl',
      status: 'generated',
      updatedAt: new Date().toISOString(),
      content: `# Terraform configuration for Unified DevOps Cloud Infrastructure
terraform {
  required_version = ">= 1.5.0"
  required_providers {
    azurerm = {
      source  = "hashicorp/azurerm"
      version = "~> 3.90"
    }
  }
  backend "azurerm" {
    resource_group_name  = "rg-devops-state"
    storage_account_name = "tfstatedevopscontrol"
    container_name       = "tfstate"
    key                  = "${appName}.tfstate"
  }
}

provider "azurerm" {
  features {}
}

resource "azurerm_resource_group" "rg" {
  name     = "rg-${appName}-prod"
  location = "eastus"
  tags = {
    Environment = "${namespace}"
    ManagedBy   = "UnifiedDevOpsAutomation"
  }
}

resource "azurerm_kubernetes_cluster" "aks" {
  name                = "aks-${appName}-eastus"
  location            = azurerm_resource_group.rg.location
  resource_group_name = azurerm_resource_group.rg.name
  dns_prefix          = "aks-${appName}"

  default_node_pool {
    name       = "default"
    node_count = ${replicas}
    vm_size    = "Standard_D2s_v5"
  }

  identity {
    type = "SystemAssigned"
  }
}`,
    });

    return artifacts;
  }
}
